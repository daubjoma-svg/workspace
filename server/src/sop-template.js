// 每个 AI 节点的 ai_prompt 都遵守「按需求规模控制篇幅」：小需求输出短、只给目标角色看得懂的内容。

'use strict';

const TEST_CASE_PROMPT =
  '研发已完成开发。请基于需求与研发改动内容，输出给测试人员可直接执行的【结构化测试用例】。\n' +
  '只输出 JSON 数组，每条固定 6 个字段：id、type(正常流/边界流/异常流)、title(用例名,≤20字)、steps(编号短句,最多3步)、expect(预期结果,一句话)、result(固定空字符串)。\n' +
  '1) 正常流覆盖研发改动的主流程;\n' +
  '2) 边界流覆盖空值/临界值/最大最小;\n' +
  '3) 异常流覆盖错误输入、无权限、依赖失败;\n' +
  '总共 5-10 条，小需求 5 条左右即可；只写测试要执行的动作和要看到的结果，不要复述需求或写实现原理。';

const PRD_PROMPT =
  '你是产品经理。请使用模板 A 生成一页纸 PRD，只允许六个章节：背景、目标、业务流程、影响范围与风险、验收标准、排期版本。\n' +
  '【按需求规模控制篇幅】小需求（单点改动、描述清晰）全文 300-600 字，每章节 1-3 条；中大需求最多 800-1200 字。需求越简单文档越短。\n' +
  '每章节只写需求中有依据的内容，没有就写「无」；禁止为凑字数扩写、禁止复述需求全文、禁止新增用户故事/接口设计/非功能要求等章节。可直接复制到飞书，不要输出 JSON、代码围栏或解释性前言。';

const DEV_PROMPT_PROMPT =
  '请汇总产品评审后的 PRD 文档与原始需求内容,结合关联模块的代码结构,生成给研发的【开发提示词】:\n' +
  '0) 【先判断是否需要前端开发】基于需求与 PRD 明确给出「是否需要前端开发：是/否」并说明理由;若不需要前端改动,明确写出「本次无需前端开发」;\n' +
  '1) 提示词拆分为【前端】与【后端】两部分,分别独立成章,便于前端与后端人员各看各的;\n' +
  '   - 【前端】章节:明确建议改动/新增的页面、组件、API 调用与状态管理位置;\n' +
  '   - 【后端】章节:明确建议改动/新增的文件、模块、类/接口、数据库变更位置;\n' +
  '2) 列出可复用的现有类/接口与需要新增的接口签名;\n' +
  '3) 只列直接服务于本方案的改动点，不罗列无关接口/文件;不要复述需求全文。\n' +
  '4) 【按需求规模裁剪】小需求（改动集中、单端）只保留「改动点 + 实施与验收」，不适用章节省略，全文 300-800 字；中大需求才展开完整内容，禁止为凑章节扩写。';

const EVALUATE_PROMPT =
  '你是资深需求评审专家。请结合客户原始诉求与其关联的业务模块,评审该需求的【合理性与可行性】:\n' +
  '1) 评估改动量(影响的功能点/接口/数据范围)并定级 L1-L4;\n' +
  '2) 估算工作量(最小-最大人日);\n' +
  '3) 需求描述中形如「【已澄清结论·视为既定事实（第 N 轮）】」的问答是发起人已确认的口径,必须直接采信,不得再问一遍、不得与其冲突;\n' +
  '4) 只有在信息缺失会导致无法判断改动范围、边界或验收口径时,才向 CSM 提出澄清问题: 只问最关键的 1-3 个,不问次要问题、不为凑轮次而提问;\n' +
  '5) 同时自评 confidence(0-1,本次结论的把握程度): 信息完整、结论确定时给高分;confidence ≥ 0.8 表示信息已足够,此时 questions 必须为空数组;\n' +
  '6) 最后输出一段给产品的需求总结(背景、目标、范围、验收口径)。\n' +
  '只输出业务结论，不展开技术实现；小需求 1-2 句总结即可，禁止为凑内容扩写。';

